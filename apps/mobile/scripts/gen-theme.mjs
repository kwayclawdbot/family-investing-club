/**
 * The theme bridge.
 *
 * gluestack ships a neutral grey semantic palette. This rewrites the `@layer theme` block in
 * global.css so every semantic token — `bg-primary`, `text-foreground`, `border-border` — resolves
 * to the FIC palette in src/theme/tokens.ts and to nothing else. The skill's semantic-tokens-only
 * rule then IS the palette law: a screen literally cannot reach a colour that is not ours.
 *
 * It also emits the brand tokens (`bg-orange`, `text-ink-2`, `border-line`) that identity
 * components need, since those are FIC's own vocabulary rather than gluestack's.
 *
 * Generated, never hand-edited:  node scripts/gen-theme.mjs  [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { tokens } from "../src/theme/tokens.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const CSS = path.resolve(here, "../global.css");

/** "#4C8C4A" → "76 140 74" — the space-separated triple NativeWind's theme layer expects. */
const rgb = (hex) => {
  const h = hex.replace("#", "");
  const n = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
  return [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16)).join(" ");
};

/**
 * gluestack's semantic role → the FIC token that plays it.
 * Orange is the CTA, green is achievement, cream is the page. Read this as the app's colour law.
 */
const SEMANTIC = {
  background: "paper",             // the screen — warm cream, never white
  foreground: "ink",
  card: "card",
  "card-foreground": "ink",
  popover: "card",
  "popover-foreground": "ink",
  primary: "orange",               // every primary action
  "primary-foreground": "creamText",
  secondary: "paper2",
  "secondary-foreground": "ink",
  muted: "paper2",
  "muted-foreground": "ink3",
  accent: "greenTint",             // progress, correctness, "you did it"
  "accent-foreground": "green",
  destructive: "red",
  "destructive-foreground": "creamText",
  border: "line",
  input: "line",
  ring: "orange",
};

/** FIC's own vocabulary, exposed as utilities for the hand-rolled identity components. */
const BRAND = Object.keys(tokens);
const kebab = (s) => s.replace(/([a-z])([0-9A-Z])/g, "$1-$2").toLowerCase();

const semanticLines = (indent) =>
  Object.entries(SEMANTIC).map(([role, tok]) => {
    if (!(tok in tokens)) { console.error(`theme bridge: unknown token "${tok}" for --${role}`); process.exit(1); }
    return `${indent}--${role}: ${rgb(tokens[tok])};`;
  }).join("\n");

const block = `@layer theme {
  /* GENERATED by scripts/gen-theme.mjs from src/theme/tokens.ts — do not edit. */

  /* FIC is a warm, light, cream-paper brand. There is no dark palette to switch to, so the app
     commits to one look rather than rendering half-inverted against a scheme it never designed. */
  :root, :root.light, :root.dark {
${semanticLines("    ")}

    /* FIC brand tokens — the identity layer's vocabulary. */
${BRAND.map((t) => `    --fic-${kebab(t)}: ${rgb(tokens[t])};`).join("\n")}
  }
}`;

const inlineBlock = `@theme inline {
${Object.keys(SEMANTIC).map((r) => `  --color-${r}: rgb(var(--${r}));`).join("\n")}

${BRAND.map((t) => `  --color-${kebab(t)}: rgb(var(--fic-${kebab(t)}));`).join("\n")}
}`;

/** Nunito is the FIC face on both builds. Loaded in app/_layout.tsx, named here. */
const fontBlock = `@theme inline {
  --font-nunito: Nunito_400Regular;
  --font-nunito-semibold: Nunito_600SemiBold;
  --font-nunito-bold: Nunito_700Bold;
  --font-nunito-extrabold: Nunito_800ExtraBold;
  --font-nunito-black: Nunito_900Black;
}`;

const css = fs.readFileSync(CSS, "utf8");
const head = css.slice(0, css.indexOf("@layer theme {"));
if (!head) { console.error("could not find @layer theme in global.css"); process.exit(1); }
const out = `${head}${block}\n\n${inlineBlock}\n\n${fontBlock}\n`;

if (process.argv.includes("--check")) {
  if (css !== out) { console.error("global.css is stale — run `npm run theme`"); process.exit(1); }
  console.log("theme bridge up to date");
} else {
  fs.writeFileSync(CSS, out);
  console.log(`bridged ${Object.keys(SEMANTIC).length} semantic roles + ${BRAND.length} brand tokens`);
}
