/**
 * tokens.ts is the single palette source for the mobile app, and it is GENERATED — never edited
 * by hand and never retyped from a screenshot. It is lifted from the web app's `globals.css`
 * `:root` block, which is where the FIC palette was originally authored, so the two builds cannot
 * drift into two slightly different greens.
 *
 *   node scripts/gen-tokens.mjs          # write src/theme/tokens.ts
 *   node scripts/gen-tokens.mjs --check  # fail if it is stale (for CI)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, "../../../src/app/globals.css");
const OUT = path.resolve(here, "../src/theme/tokens.ts");

const css = fs.readFileSync(SRC, "utf8");
const root = /:root\s*\{([\s\S]*?)\n\}/.exec(css);
if (!root) { console.error("could not find :root in", SRC); process.exit(1); }

/** `--green-2: #4C8C4A;  /* progress fill *\/` → { name, value, note } */
const entries = [];
for (const line of root[1].split("\n")) {
  const m = /^\s*--([a-z0-9-]+)\s*:\s*([^;]+);\s*(?:\/\*\s*(.*?)\s*\*\/)?/i.exec(line);
  if (!m) continue;
  entries.push({ name: m[1], value: m[2].trim(), note: m[3] || null });
}
if (entries.length < 20) { console.error(`only ${entries.length} tokens parsed — refusing`); process.exit(1); }

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const body = entries.map((e) => `  ${camel(e.name)}: "${e.value}",${e.note ? ` // ${e.note}` : ""}`).join("\n");

const out = `/**
 * FIC palette — GENERATED by scripts/gen-tokens.mjs from the web app's globals.css.
 * Do not edit by hand; run \`npm run tokens\` instead.
 *
 * This is the single source the gluestack theme bridges to. Semantic tokens
 * (bg-primary, text-foreground, border-border …) resolve to these values and nowhere else.
 */

export const tokens = {
${body}
} as const;

export type TokenName = keyof typeof tokens;

/** The CSS custom-property name a token was authored under, for the NativeWind theme bridge. */
export const cssVarName: Record<TokenName, string> = {
${entries.map((e) => `  ${camel(e.name)}: "--${e.name}",`).join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== out) { console.error("tokens.ts is stale — run `npm run tokens`"); process.exit(1); }
  console.log(`tokens.ts up to date (${entries.length} tokens)`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} — ${entries.length} tokens`);
}
